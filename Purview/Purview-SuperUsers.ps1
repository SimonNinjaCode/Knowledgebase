Connect-Aipservice

## Check existing Super Users
Get-AipServiceSuperUser 

## Check existing Super User Group
Get-AipServiceSuperUserGroup 

## Enable Super User Features
Enable-AipServiceSuperUserFeature

## Disable Super User Features
Disable-AipServiceSuperUserFeature

## Set specific user as Super User
Add-AipServiceSuperUser 

## Set specific group as Super User Group
Set-AipServiceSuperUserGroup

